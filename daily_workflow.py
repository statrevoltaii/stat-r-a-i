
import sys
import json
import os
import subprocess
import time
from pathlib import Path
from dotenv import load_dotenv

# Add the root directory to sys.path
current_dir = Path(__file__).parent.absolute()
root_dir = current_dir.parent.absolute()
sys.path.append(str(current_dir))
sys.path.append(str(root_dir))

# Import upload functions (assuming these exist in root/upload/)
try:
    from upload.upload_instagram import upload_to_instagram
    from upload.upload_facebook import upload_to_facebook
    from upload.upload_threads import upload_to_threads
    from upload.upload_to_youtube import upload_to_youtube
    from upload.upload_twitter import upload_to_twitter
    print("✅ Successfully imported all upload modules.")
except ImportError as e:
    print(f"❌ Import error: {e}")
    # Don't exit, try to run what we can or rely on what's available
    pass

def run_command(command, cwd=None):
    print(f"🚀 Running: {command}")
    try:
        subprocess.run(command, check=True, shell=True, cwd=cwd)
        print("✅ Command finished successfully.")
    except subprocess.CalledProcessError as e:
        print(f"❌ Command failed: {e}")
        sys.exit(1)

def main():
    # Load .env from root
    load_dotenv(dotenv_path=current_dir / '.env')
    
    # Paths
    data_file = current_dir / "current_topic.json"
    video_path = current_dir / "recording.mp4"
    
    # ROBUSTNESS: Check if topic was already generated by an orchestrator (like GitHub Actions)
    skip_gen = "--skip-generation" in sys.argv
    
    # 1. Generate New Topic
    if not skip_gen:
        print("\n" + "="*50)
        print("🎨 STEP 1: GENERATING NEW TOPIC")
        print("="*50)
        
        # Delete old topic file to ensure fresh generation
        if data_file.exists():
            print(f"🗑️ Deleting old topic file at {data_file}")
            data_file.unlink()
            
        run_command("node generate_topic.js", cwd=current_dir)
    else:
        print("\n⏭️ STEP 1 SKIPPED: Using pre-generated topic (Robust Mode)")
    
    if not data_file.exists():
        print(f"❌ CRITICAL ERROR: Topic file not found at {data_file}")
        sys.exit(1)
        
    with open(data_file, 'r', encoding='utf-8') as f:
        topic_data = json.load(f)
        
    print(f"✅ Topic Generated: {topic_data.get('topic')} ")

    # 2. Extract Metadata (Robustly)
    title = topic_data.get("topic", "StatRevoltAI Comparison")
    tagline = topic_data.get("description", "Daily Data Visualization")
    
    # Get Hashtags (Array or Parse)
    raw_tags = topic_data.get("hashtags", [])
    if not raw_tags or not isinstance(raw_tags, list):
        # Fallback parsing
        import re
        all_text = (topic_data.get("instagram_caption", "") + " " + topic_data.get("youtube_description", ""))
        raw_tags = re.findall(r"#\w+", all_text)
    
    # Ensure lowercase
    hashtags_list = [t.lower() for t in raw_tags]
    hashtags_str = " ".join(hashtags_list)
    
    # Platform Texts
    yt_desc = topic_data.get("youtube_description", f"{tagline}\n\n{hashtags_str}")
    ig_caption = topic_data.get("instagram_caption", f"{title}\n\n{tagline}\n\n{hashtags_str}")
    fb_caption = topic_data.get("facebook_caption", f"{title}\n{tagline}\n{hashtags_str}")
    threads_caption = topic_data.get("threads_caption", f"{title}\n{hashtags_str}")
    tw_caption = topic_data.get("twitter_caption", f"{title} {hashtags_str}")
    
    print("✅ Metadata Prepared.")
    
    # 3. Record Video
    print("\n" + "="*50)
    print("🎥 STEP 3: RECORDING VIDEO")
    print("="*50)
    
    # Delete old video if exists to ensure we don't upload stale content
    if video_path.exists():
        print(f"🗑️ Deleting old recording at {video_path}")
        video_path.unlink()
        
    run_command("node capture_demo.js", cwd=current_dir)
    
    if not video_path.exists():
        print(f"❌ Failed to record video at {video_path}")
        sys.exit(1)
        
    print(f"✅ Video Recorded: {video_path}")
    
    # 4. Upload to Social Media
    print("\n" + "="*50)
    print("🚀 STEP 4: UPLOADING TO SOCIAL MEDIA")
    print("="*50)

    # --- YouTube ---
    print("\n🎬 [1/5] UPLOADING TO YOUTUBE...")
    try:
        # YouTube tags need to be a list without # usually, but let's strip
        yt_tags = [t.replace("#", "") for t in hashtags_list]
        print(f"📝 YouTube Title: {title}")
        print(f"📝 YouTube Description Length: {len(yt_desc)} characters")
        print(f"📊 YouTube Tags: {yt_tags[:5]}...")
        upload_to_youtube(
            video_path=video_path,
            title=title,
            description=yt_desc,
            tags=yt_tags,
            category_id='28'
        )
        print("✅ YouTube Upload Complete!")
    except Exception as e:
        print(f"❌ YouTube upload failed: {e}")

    # --- Instagram ---
    print("\n📸 [2/5] UPLOADING TO INSTAGRAM...")
    try:
        print(f"📝 Instagram Caption Preview (first 200 chars): {ig_caption[:200]}...")
        print(f"📊 Caption Length: {len(ig_caption)} characters")
        
        # Upload as Reel (NOT to main grid, only to Reels tab)
        print("\n🎬 Uploading Instagram REEL (with full caption)...")
        upload_to_instagram(str(video_path), ig_caption, is_story=False)
        print("✅ Instagram Reel Upload Complete!")
        
        # Upload as Story (Stories don't support captions via API)
        print("\n📸 Uploading Instagram STORY (no caption - API limitation)...")
        upload_to_instagram(str(video_path), ig_caption, is_story=True)
        print("✅ Instagram Story Upload Complete!")
    except Exception as e:
        print(f"❌ Instagram upload failed: {e}")

    # --- Facebook ---
    print("\n📘 [3/5] UPLOADING TO FACEBOOK...")
    try:
        from upload.upload_facebook import upload_to_facebook_story
        print(f"📝 Facebook Caption Preview (first 200 chars): {fb_caption[:200]}...")
        print(f"📊 Caption Length: {len(fb_caption)} characters")
        print(f"📝 Facebook Title: {title}")
        
        upload_to_facebook(str(video_path), fb_caption, title=title)
        print("✅ Facebook Reel Upload Complete!")
        
        # ADDED: Upload as Facebook Story
        print("\n📸 Uploading Facebook Story...")
        upload_to_facebook_story(str(video_path))
        print("✅ Facebook Story Upload Complete!")
    except Exception as e:
        print(f"❌ Facebook upload failed: {e}")

    # --- Threads ---
    print("\n🧵 [4/5] UPLOADING TO THREADS...")
    try:
        print(f"📝 Threads Text Preview (first 200 chars): {threads_caption[:200]}...")
        print(f"📊 Text Length: {len(threads_caption)} characters")
        
        upload_to_threads(str(video_path), threads_caption)
        print("✅ Threads Upload Complete!")
    except Exception as e:
        print(f"❌ Threads upload failed: {e}")

    # --- Twitter ---
    print("\n🐦 [5/5] UPLOADING TO TWITTER...")
    try:
        # Twitter limit check
        tw_caption_final = tw_caption[:280]  # Enforce Twitter limit
        if len(tw_caption) > 280:
             tw_caption_final = f"{title}\n" + " ".join(hashtags_str.split()[:3])
        
        print(f"📝 Twitter Text: {tw_caption_final}")
        print(f"📊 Text Length: {len(tw_caption_final)} characters")

        upload_to_twitter(str(video_path), tw_caption_final)
        print("✅ Twitter Upload Complete!")
    except Exception as e:
        print(f"❌ Twitter upload failed: {e}")

    print("\n" + "="*50)
    print("🏁 STATREVOLT-AI DAILY AUTOMATION COMPLETED!")
    print("="*50)

if __name__ == "__main__":
    main()
